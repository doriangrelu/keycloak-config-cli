package io.github.doriangrelu.keycloak.config.application.definition;

import io.github.doriangrelu.keycloak.config.application.common.ApplicationException;

/** The name of a realm folder is not a plain name: it could leave the root or hide the folder. */
public final class InvalidRealmFolderException extends ApplicationException {

    public InvalidRealmFolderException(final String folder) {
        super("Invalid realm folder '" + folder + "': use letters, digits, '.', '_' or '-', starting with a letter or"
                + " a digit");
    }
}
